export interface SkillIntent {
  id: string;
  description: string;
  /**
   * Embedded at load time and used for routing. Not documentation.
   * Write them the way you actually speak, including terse and sloppy forms.
   * Five to eight per intent.
   */
  examples: string[];
  lanes: Lane[];
  requiresCamera?: boolean;
}

export interface SkillManifest {
  id: string;
  version: string;
  description: string;
  intents: SkillIntent[];
  capabilities: Capability[];
  /** Labels the skill in the dashboard and tightens gate defaults. */
  sensitivity?: "normal" | "personal";
}

export type SkillStatus = "loaded" | "disabled";

export interface SkillHealth {
  id: string;
  version: string;
  status: SkillStatus;
  lastError?: string;
  loadedAt?: number;
}

/** Logged for every dispatch. When the wrong skill fires, this says why. */
export interface SkillRoutingTrace {
  utterance: string;
  lane: Lane;
  candidates: { skillId: string; intentId: string; score: number }[];
  chosen?: { skillId: string; intentId: string };
  /** True when the embedding match was ambiguous and a model broke the tie. */
  disambiguated: boolean;
}

// ---------------------------------------------------------------------------
// Nutrition — quantities are declared, never estimated. ADR-011.
// ---------------------------------------------------------------------------

export interface FoodItem {
  name: string;
  /** Absent when the owner did not give one. Never filled in by a model. */
  quantity?: Measurement;
  /** Only present when the lookup table had a hit for this food and quantity. */
  nutrition?: {
    kcal: number;
    proteinG: number;
    carbsG: number;
    fatG: number;
    source: "openfoodfacts" | "usda";
  };
  /** Set when vision proposed the name and the owner accepted or corrected it. */
  identifiedBy?: "owner" | "vision-confirmed" | "vision-corrected";
}

export interface MealLog {
  id: string;
  at: number;
  items: FoodItem[];
  /** Frame retained only if the owner approved keeping it. */
  framePath?: string;
  confirmedAt: number;
}
