// ---------------------------------------------------------------------------
// Router
// ---------------------------------------------------------------------------

export type Lane = "reflex" | "converse" | "reason" | "see" | "act";

export type CostTier = "free-local" | "free-remote" | "paid";

export interface ChatRequest {
  lane: Lane;
  system: string;
  messages: ChatMessage[];
  /** Ask the provider for strict JSON. Providers that cannot must reject. */
  jsonSchema?: object;
  maxTokens?: number;
  temperature?: number;
  /** Hard deadline. The router aborts and falls through on expiry. */
  timeoutMs: number;
}

export interface ChatMessage {
  role: "system" | "user" | "assistant";
  content: string;
}

export interface ChatChunk {
  delta: string;
  done: boolean;
}

export interface VisionRequest {
  imagePath: string;
  prompt: string;
  /** When set, the provider must return JSON matching this shape. */
  jsonSchema?: object;
  timeoutMs: number;
}

export interface VisionResult {
  /** What was seen, in words. This is the durable record. Always present. */
  qualitative: string;
  /** Optional structured extraction. May be null if the model was unsure. */
  structured: object | null;
  /** Honest self-assessment, 0..1. Providers that cannot produce this return 0.5. */
  confidence: number;
}

/** Emitted for every router call. This is how we learn what to change. */
export interface RouterTrace {
  requestId: string;
  lane: Lane;
  providerId: string;
  costTier: CostTier;
  latencyMs: number;
  /** 0 = first choice served it. >0 = fallbacks were used. */
  fallbackDepth: number;
  ok: boolean;
  error?: string;
}

// ---------------------------------------------------------------------------
// Capabilities and the gate
// ---------------------------------------------------------------------------

export type Capability =
  // green — automatic, still logged
  | "MEMORY_READ"
  | "FS_READ"
  | "CAMERA"
  | "NET_READ"
  // yellow — requires approval
  | "MEMORY_WRITE"
  | "FS_WRITE"
  | "GIT_WRITE"
  | "SHELL_EXEC"
  | "WEBHOOK";
// red capabilities are deliberately absent from this union. They are not
// reachable by any code path. Adding one here is a security decision.

export const GREEN_CAPABILITIES: readonly Capability[] = [
  "MEMORY_READ",
  "FS_READ",
  "CAMERA",
  "NET_READ",
] as const;

export type ApprovalState =
  | "pending"
  | "approved"
  | "rejected"
  | "expired"
  | "executed";

export interface ApprovalRequest {
  id: string; // ulid
  /** Single use. Spending it twice fails closed and logs a replay event. */
  nonce: string;
  createdAt: number;
  expiresAt: number;
  capability: Capability;
  skillId: string;
  /**
   * What the owner reads before deciding. Generated by the `converse` lane.
   * A misleading summary is a security hole — this text is the security
   * boundary, not the payload.
   */
  humanSummary: string;
  /** The full thing, shown on expand. */
  payload: unknown;
  /** Rendered as a diff in the dashboard when present. */
  diff?: string;
  state: ApprovalState;
}

export interface ApprovalResponse {
  requestId: string;
  nonce: string;
  decision: "approve" | "reject";
  decidedAt: number;
}

export type ApprovalOutcome =
  | { ok: true; result: unknown }
  | { ok: false; reason: "rejected" | "expired" | "replay" | "error"; detail?: string };

/** A skill produces these. It never produces an action. */
export interface ProposedAction {
  capability: Capability;
  humanSummary: string;
  payload: unknown;
  diff?: string;
  /** Overrides the 5-minute default. */
  expiresInMs?: number;
}

/** Signed envelope handed to an executor. Executors verify before acting. */
export interface SignedExecution {
  requestId: string;
  nonce: string;
  payload: unknown;
  issuedAt: number;
  /** HMAC-SHA256 over {requestId, nonce, payload, issuedAt}. */
  signature: string;
}

